# -*- coding: utf-8 -*-
# Generates src/lang_table.inc from tools/translations.py.
#   python tools/gen_lang.py
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from translations import ROWS  # noqa: E402

COLS = ["en", "tr", "fr", "de", "ar", "zh_hant", "zh_hans"]


def normalize(row):
    """Rows are (en, tr, fr, de, ar, hant, hans); a row whose Turkish is None carries it as an 8th item."""
    row = list(row)
    if row[1] is None:
        row[1] = row[7]
    return row[:7]


def spec(s):
    return re.findall(r"%[-+ #0]*\d*(?:\.\d+)?[a-zA-Z%]", s)


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    seen = set()
    out = ["// Generated by tools/gen_lang.py from tools/translations.py. Do not edit.",
           "// Columns: " + ", ".join(COLS)]
    errors = 0
    for raw in ROWS:
        row = normalize(raw)
        key = row[0]
        if key in seen:
            print("duplicate key:", key)
            errors += 1
        seen.add(key)
        for col, text in zip(COLS, row):
            if text is None:
                print("missing", col, "for", key)
                errors += 1
            elif spec(text) != spec(key):
                print("format mismatch in", col, ":", key, "|", text)
                errors += 1
        out.append("{" + ", ".join("u8" + c_str(t) for t in row) + "},")
    path = os.path.join(HERE, "..", "src", "lang_table.inc")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(ROWS)} strings, {errors} problems -> {os.path.normpath(path)}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
